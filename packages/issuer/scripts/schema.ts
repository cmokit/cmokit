// Writes src/schema.ts: the tables Better Auth needs for the issuer's configuration, as SQL, so the
// Worker makes them without asking the database what it holds. Run it after changing auth.ts or
// upgrading Better Auth; a test fails while the two disagree.
//
//   node --conditions=cmokit-source --import ./scripts/tsx.ts packages/issuer/scripts/schema.ts

import { writeFileSync } from 'node:fs';
import { schemaFor } from '../test/helpers.ts';

const statements = await schemaFor();
writeFileSync(new URL('../src/schema.ts', import.meta.url), `// Generated by scripts/schema.ts from Better Auth's own migrations for the issuer's configuration
// (auth.ts). Every statement makes a table or index only when it is missing, so running them again
// changes nothing.

export const SCHEMA: readonly string[] = ${JSON.stringify(statements, null, 2)};
`);
console.log(`Wrote ${statements.length} statements.`);
