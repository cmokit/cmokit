import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  CONVERT_PATH, LEADS_PATH, LEAD_COOKIE, LIFECYCLE_EVENT, LIFECYCLE_LEAD, PREVIEW_PARAM, RELAY_PATH,
  VISITOR_COOKIE, variantCookie,
} from '../packages/cli/src/index.ts';

const target = join(import.meta.dirname, '..', 'docs', 'explanation', 'architecture.md');
